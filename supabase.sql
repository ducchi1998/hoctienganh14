-- 1) Hồ sơ người dùng: mọi tài khoản đăng ký mới mặc định là học sinh.
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  role text not null default 'student' check (role in ('student','teacher')),
  created_at timestamptz not null default now()
);

create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = ''
as $$
begin
  insert into public.profiles (id, role) values (new.id, 'student')
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute procedure public.handle_new_user();

create table if not exists public.lessons (
  id bigint generated by default as identity primary key,
  title text not null,
  category text not null,
  grade text,
  description text,
  resource_url text,
  video_url text,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

alter table public.profiles enable row level security;
alter table public.lessons enable row level security;

-- Người dùng đã đăng nhập có thể đọc hồ sơ của chính mình.
drop policy if exists "Read own profile" on public.profiles;
create policy "Read own profile" on public.profiles for select to authenticated
using (id = (select auth.uid()));

-- Chỉ giáo viên mới được tạo, sửa, xóa bài học.
drop policy if exists "Authenticated users read lessons" on public.lessons;
create policy "Authenticated users read lessons" on public.lessons for select to authenticated
using (true);

drop policy if exists "Teachers insert lessons" on public.lessons;
create policy "Teachers insert lessons" on public.lessons for insert to authenticated
with check (
  created_by = (select auth.uid()) and
  exists (select 1 from public.profiles p where p.id = (select auth.uid()) and p.role = 'teacher')
);

drop policy if exists "Teachers update lessons" on public.lessons;
create policy "Teachers update lessons" on public.lessons for update to authenticated
using (exists (select 1 from public.profiles p where p.id = (select auth.uid()) and p.role = 'teacher'))
with check (exists (select 1 from public.profiles p where p.id = (select auth.uid()) and p.role = 'teacher'));

drop policy if exists "Teachers delete lessons" on public.lessons;
create policy "Teachers delete lessons" on public.lessons for delete to authenticated
using (exists (select 1 from public.profiles p where p.id = (select auth.uid()) and p.role = 'teacher'));

