-- Học sinh chỉ nhận câu hỏi và lựa chọn, không nhận đáp án đúng.
create or replace function public.get_lesson_quiz(p_lesson_id bigint)
returns jsonb language plpgsql security definer set search_path = public
as $$
declare v_quiz public.lesson_quizzes%rowtype;
begin
  if auth.uid() is null then raise exception 'Bạn cần đăng nhập để làm trắc nghiệm.'; end if;
  select * into v_quiz from public.lesson_quizzes where lesson_id = p_lesson_id;
  if not found then return null; end if;
  return jsonb_build_object(
    'id', v_quiz.id, 'lesson_id', v_quiz.lesson_id, 'title', v_quiz.title,
    'questions', coalesce((
      select jsonb_agg(jsonb_build_object('text', q.value->'text', 'options', q.value->'options') order by q.ordinality)
      from jsonb_array_elements(v_quiz.questions) with ordinality as q(value, ordinality)
    ), '[]'::jsonb)
  );
end; $$;

create or replace function public.submit_lesson_quiz(p_lesson_id bigint, p_answers jsonb)
returns jsonb language plpgsql security definer set search_path = public
as $$
declare v_quiz public.lesson_quizzes%rowtype; v_total integer; v_score integer := 0;
        v_i integer; v_question jsonb; v_selected integer; v_attempt_id bigint;
begin
  if auth.uid() is null then raise exception 'Bạn cần đăng nhập để nộp bài.'; end if;
  if p_answers is null or jsonb_typeof(p_answers) <> 'object' then raise exception 'Dữ liệu đáp án không hợp lệ.'; end if;
  select * into v_quiz from public.lesson_quizzes where lesson_id = p_lesson_id;
  if not found then raise exception 'Bài học chưa có trắc nghiệm.'; end if;
  v_total := jsonb_array_length(v_quiz.questions);
  if v_total < 1 then raise exception 'Bài trắc nghiệm chưa có câu hỏi.'; end if;
  for v_i in 0..(v_total - 1) loop
    v_question := v_quiz.questions->v_i;
    if p_answers ? v_i::text then
      begin v_selected := (p_answers->>v_i::text)::integer;
      exception when others then v_selected := -1; end;
      if v_selected between 0 and 3 and v_selected = (v_question->>'correct')::integer then v_score := v_score + 1; end if;
    end if;
  end loop;
  insert into public.quiz_attempts(lesson_id, quiz_id, user_id, answers, score, total_questions)
  values(p_lesson_id, v_quiz.id, auth.uid(), p_answers, v_score, v_total)
  returning id into v_attempt_id;
  return jsonb_build_object('attempt_id',v_attempt_id,'score',v_score,'total',v_total,'percent',round(v_score::numeric * 100 / v_total));
end; $$;
revoke all on function public.get_lesson_quiz(bigint) from public;
revoke all on function public.submit_lesson_quiz(bigint,jsonb) from public;
grant execute on function public.get_lesson_quiz(bigint) to authenticated;
grant execute on function public.submit_lesson_quiz(bigint,jsonb) to authenticated;
